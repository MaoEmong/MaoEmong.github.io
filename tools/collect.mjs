import fs from 'node:fs/promises';
import path from 'node:path';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const run=promisify(execFile);
const root=path.resolve(import.meta.dirname,'..');
const cache=path.join(root,'.work/readmes');
await fs.mkdir(cache,{recursive:true});
const gh=async(args)=>(await run('gh',args,{encoding:'utf8',maxBuffer:8*1024*1024,windowsHide:true})).stdout;
const excluded=new Set(['MaoEmong','interview-study','ieum-models','MaoEmong.github.io','synapse-design-preview']);
const all=JSON.parse(await gh(['repo','list','MaoEmong','--limit','1000','--json','name,description,visibility,url,defaultBranchRef']));
const repos=all.filter(r=>r.visibility==='PUBLIC'&&!excluded.has(r.name));
let index=0;const results=[];
await Promise.all(Array.from({length:5},async()=>{while(index<repos.length){const repo=repos[index++];
 const text=await gh(['api',`repos/MaoEmong/${repo.name}/readme`,'-H','Accept: application/vnd.github.raw+json']);
 await fs.writeFile(path.join(cache,repo.name+'.md'),text);
 const images=[...text.matchAll(/!\[[^\]]*\]\(([^\s)]+)(?:\s+[^)]*)?\)|<img\b[^>]*src=["']([^"']+)["']/g)].map(m=>m[1]||m[2]);
 results.push({...repo,headings:text.split(/\r?\n/).filter(l=>/^#{1,3} /.test(l)),images});
}}));
await fs.writeFile(path.join(root,'.work/inventory.json'),JSON.stringify(results,null,2));
for(const r of results)console.log(JSON.stringify({name:r.name,images:r.images.slice(0,4),headings:r.headings.slice(0,12)}));
